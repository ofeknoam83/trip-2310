// ---------- helpers ----------
export function distKm(a, b) {
  const R = 6371, r = Math.PI / 180;
  const dLat = (b.lat - a.lat) * r, dLng = (b.lng - a.lng) * r;
  const x = Math.sin(dLat / 2) ** 2 + Math.cos(a.lat * r) * Math.cos(b.lat * r) * Math.sin(dLng / 2) ** 2;
  return 2 * R * Math.asin(Math.sqrt(x));
}
export function regionAt(pos) {
  return REGIONS.find((g) => pos.lat >= g.box[0] && pos.lat <= g.box[2] && pos.lng >= g.box[1] && pos.lng <= g.box[3]) || null;
}
// Where are we: the place we're inside (smallest radius wins), plus the nearest others
export function locate(pos) {
  const ranked = PLACES.map((p) => ({ ...p, d: distKm(pos, p) })).sort((a, b) => a.d - b.d);
  const inside = ranked.filter((p) => p.d <= p.r).sort((a, b) => a.r - b.r)[0] || null;
  const region = (inside && REGIONS.find((g) => g.id === inside.region)) || regionAt(pos);
  return { inside, nearest: ranked.filter((p) => p !== inside && p.id !== inside?.id).slice(0, 4), region };
}
